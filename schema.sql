CREATE TABLE IF NOT EXISTS articles(id INTEGER PRIMARY KEY AUTOINCREMENT,slug TEXT UNIQUE,sec TEXT,title TEXT,img TEXT,body TEXT,faq TEXT,created INTEGER);
CREATE TABLE IF NOT EXISTS products(id INTEGER PRIMARY KEY AUTOINCREMENT,sec TEXT,name TEXT,price TEXT,img TEXT,link TEXT);
CREATE TABLE IF NOT EXISTS settings(k TEXT PRIMARY KEY,v TEXT);
CREATE INDEX IF NOT EXISTS ix_created ON articles(created);
